// Node 24+. Dry run by default; --generate designs previews, --save N saves one.
// No cloning, account upgrades, voice deletion, or automatic retries.
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { pathToFileURL } from 'node:url';
import { voiceDesigns } from '../src/content/voice-designs.ts';
import { designedVoices } from '../src/content/designed-voices.ts';
import { voiceCast } from '../src/content/narration.ts';
import { getNarrationSegments } from '../src/lib/narration.ts';

const args = process.argv.slice(2);
const speaker = args[0] === 'idris' ? 'adil' : args[0] === 'sinna' ? 'virello' : args[0];
if (!speaker) {
  for (const [id, design] of Object.entries(voiceDesigns)) console.log(`${id}: ${voiceCast[id].name} — ${designedVoices[id] ? 'saved design' : 'stock audition; design pending'} — worldbuilding/characters/${design.profile}.md`);
  process.exit(0);
}
const design = voiceDesigns[speaker];
assert(design, 'Choose a named cast member (idris and sinna aliases are supported).');
assert(design.description.length >= 20 && design.description.length <= 1000);
const model = 'eleven_ttv_v3';
const designHash = createHash('sha256').update(JSON.stringify({ model, description: design.description })).digest('hex');
const name = `Chronicle — ${voiceCast[speaker].name} — ${designHash.slice(0, 8)}`;
const folder = path.resolve('public/audio/voices', speaker);
const ledgerPath = path.join(folder, `${designHash.slice(0, 16)}.json`);
const bindingPath = path.resolve('src/content/designed-voices.ts');
const lines = [];
for (const file of fs.readdirSync('src/content/chapters').filter(file => /^\d.*\.ts$/.test(file))) {
  const chapterModule = await import(pathToFileURL(path.resolve('src/content/chapters', file)).href);
  const chapter = Object.values(chapterModule).find(value => value?.slug && value?.scenes);
  for (const segment of getNarrationSegments(chapter).filter(segment => segment.speaker === speaker)) {
    lines.push({ text: segment.text, chapter: chapter.slug, scene: segment.sceneId });
    if (lines.map(line => line.text).join(' ').length >= 240) break;
  }
  if (lines.map(line => line.text).join(' ').length >= 240) break;
}
const excerpt = lines.map(line => line.text).join(' ');
assert(excerpt.length, 'No reviewed dialogue for a design audition.');
// Brief roles repeat their own lines to meet the provider minimum.
const text = (excerpt + ' ').repeat(Math.max(1, Math.ceil(101 / (excerpt.length + 1)))).trim().slice(0, 1000);
console.log(`${name}\n${design.description}\nAudition: ${text.length} manuscript characters.`);
if (!args.includes('--generate') && !args.includes('--save')) process.exit(0);
assert(process.env.ELEVENLABS_API_KEY, 'Set ELEVENLABS_API_KEY in ignored .env.local.');
const headers = { 'xi-api-key': process.env.ELEVENLABS_API_KEY, 'Content-Type': 'application/json' };
async function request(endpoint, body) {
  const response = await fetch(`https://api.elevenlabs.io/v1/${endpoint}`, {
    method: body ? 'POST' : 'GET', headers, body: body ? JSON.stringify(body) : undefined,
    signal: AbortSignal.timeout(60000),
  });
  if (!response.ok) {
    const error = await response.json().catch(() => ({}));
    throw new Error(`ElevenLabs HTTP ${response.status}: ${error.detail?.message ?? error.detail?.status ?? 'request failed'}. No automatic retry.`);
  }
  return response.json();
}
const subscription = await request('user/subscription');
const { voices } = await request('voices');
assert(Array.isArray(voices), 'Voice inventory unavailable.');
function saveBinding(voiceId) {
  designedVoices[speaker] = { voiceId, designHash, name };
  fs.writeFileSync(bindingPath, '/** Saved ElevenLabs identities. Generated by scripts/design-character-voices.mjs. */\nexport const designedVoices: Record<string, { voiceId: string; designHash: string; name: string }> = ' + JSON.stringify(designedVoices, null, 2) + ';\n');
}
const existing = voices.find(voice => voice.name === name);
if (existing) {
  saveBinding(existing.voice_id);
  console.log('Recovered existing saved identity; no credits used.');
  process.exit(0);
}
assert(subscription.tier !== 'free', 'ElevenLabs requires a paid plan for Voice Design through the API. No plan change was made.');
const used = voices.filter(voice => voice.category !== 'premade').length;
assert(Number.isFinite(subscription.voice_limit) && used < subscription.voice_limit,
  `No saved voice slots available (${used}/${subscription.voice_limit}). Existing voices were preserved.`);
let ledger = fs.existsSync(ledgerPath) ? JSON.parse(fs.readFileSync(ledgerPath, 'utf8')) : null;
if (args.includes('--generate') && !ledger) {
  assert(Number.isFinite(subscription.character_limit) && Number.isFinite(subscription.character_count));
  assert(subscription.character_limit - subscription.character_count >= text.length * 3, 'Insufficient included allowance for previews.');
  // Persist an attempt marker before a potentially billed request. Inspect uncertain outcomes manually.
  fs.mkdirSync(folder, { recursive: true });
  const attemptPath = path.join(folder, `${designHash.slice(0, 16)}.pending.json`);
  assert(!fs.existsSync(attemptPath), 'A previous design request has an uncertain result; inspect it before retrying.');
  fs.writeFileSync(attemptPath, JSON.stringify({ name, designHash, attemptedAt: new Date().toISOString() }, null, 2) + '\n');
  const result = await request('text-to-voice/design?output_format=mp3_44100_128', {
    voice_description: design.description, model_id: model, text, seed: 42,
    guidance_scale: 5, loudness: 0.5,
  });
  assert(result.previews?.length, 'Provider returned no previews.');
  ledger = {
    provider: 'ElevenLabs', model, name, speaker, designHash, description: design.description,
    profile: `worldbuilding/characters/${design.profile}.md`,
    profileHash: createHash('sha256').update(fs.readFileSync(`worldbuilding/characters/${design.profile}.md`)).digest('hex'),
    auditionText: result.text, repeatedExcerpt: excerpt.length < 100, manuscriptSources: lines.map(({ chapter, scene }) => ({ chapter, scene })),
    generatedAt: new Date().toISOString(), tier: subscription.tier,
    license: subscription.tier === 'free' ? 'Noncommercial only; attribution elevenlabs.io in published title.' : 'Generated under account paid plan; see ElevenLabs terms.',
    licenseSource: 'https://help.elevenlabs.io/hc/en-us/articles/13313564601361-Can-I-publish-the-content-I-generate-on-the-platform',
    previews: result.previews.map((preview, index) => {
      const audio = Buffer.from(preview.audio_base_64, 'base64');
      assert(audio.length > 1000, 'Empty preview.');
      const file = `${designHash.slice(0, 16)}-${index + 1}.mp3`;
      fs.writeFileSync(path.join(folder, file), audio);
      return { file, generatedVoiceId: preview.generated_voice_id, duration: preview.duration_secs, bytes: audio.length };
    }),
  };
  fs.writeFileSync(ledgerPath, JSON.stringify(ledger, null, 2) + '\n');
  fs.unlinkSync(attemptPath);
}
assert(ledger, 'Generate previews first using --generate.');
console.log(`Previews: ${ledger.previews.map(preview => path.join(folder, preview.file)).join('\n')}`);
if (args.includes('--save')) {
  const index = Number(args[args.indexOf('--save') + 1]) - 1;
  assert(Number.isInteger(index) && ledger.previews[index], 'Choose a preview number beginning at 1.');
  const voice = await request('text-to-voice', {
    voice_name: name, voice_description: design.description,
    generated_voice_id: ledger.previews[index].generatedVoiceId,
  });
  assert(voice.voice_id, 'No saved voice ID returned.');
  ledger.selectedPreview = index + 1;
  ledger.voiceId = voice.voice_id;
  fs.writeFileSync(ledgerPath, JSON.stringify(ledger, null, 2) + '\n');
  saveBinding(voice.voice_id);
  console.log(`Saved and assigned ${voiceCast[speaker].name}: ${voice.voice_id}`);
}
